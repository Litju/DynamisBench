"""Integrity-checked, read-only views of the packaged laboratory dataset.

Layout (package data, generated by ``python/tools/mujoco_squat_laboratory.py --write``)::

    data/manifest.json                 dataset identity, recordings index, file digests
    data/model.json                    the compiled model as plain data
    data/recordings/<id>.json.gz       one recording: metadata, checks, frame columns

The manifest's raw bytes are pinned by :data:`MANIFEST_SHA256`, and every other file is pinned
by the manifest. A file that is absent or differs is refused with :class:`LaboratoryDataError`
rather than served: the workbench never displays a recording it cannot attribute.
"""

from __future__ import annotations

import functools
import gzip
import hashlib
import json
from importlib.resources import files
from typing import Any, Final

__all__ = [
    "DATASET_ID",
    "DATASET_SCHEMA",
    "FRAME_GROUPS",
    "MANIFEST_SHA256",
    "LaboratoryDataError",
    "frame_columns",
    "laboratory_index",
    "laboratory_model",
    "recording_view",
]

DATASET_SCHEMA: Final = "dynamisbench.laboratory.dataset/1"
DATASET_ID: Final = "laboratory/1"
MANIFEST_SHA256: Final = "69bd013b3444e6b3993a15b46dfb19e394589a037cfd72701f74ba0208467bd9"
"""Raw-byte SHA-256 of ``data/manifest.json``. A changed pin is a reviewed dataset change."""

FRAME_GROUPS: Final = ("pose", "kinematics", "kinetics")
"""The transport groups of a recording's frame columns."""

_PACKAGE: Final = "dynamisbench.laboratory"


class LaboratoryDataError(Exception):
    """The packaged laboratory dataset is absent, altered, or does not contain the request."""


def _read(relative: str) -> bytes:
    try:
        return files(_PACKAGE).joinpath("data", relative).read_bytes()
    except (FileNotFoundError, OSError) as error:
        raise LaboratoryDataError(
            f"the laboratory dataset file {relative!r} is unavailable"
        ) from error


@functools.cache
def _manifest() -> dict[str, Any]:
    content = _read("manifest.json")
    digest = hashlib.sha256(content).hexdigest()
    if digest != MANIFEST_SHA256:
        raise LaboratoryDataError(
            f"the laboratory manifest digest {digest} is not the reviewed {MANIFEST_SHA256}"
        )
    manifest = json.loads(content)
    if manifest.get("schema") != DATASET_SCHEMA or manifest.get("dataset_id") != DATASET_ID:
        raise LaboratoryDataError("the laboratory manifest is not the expected dataset")
    return manifest


def _verified(relative: str) -> bytes:
    expected = _manifest()["files"].get(relative)
    if expected is None:
        raise LaboratoryDataError(f"the laboratory manifest does not list {relative!r}")
    content = _read(relative)
    if hashlib.sha256(content).hexdigest() != expected:
        raise LaboratoryDataError(f"the laboratory dataset file {relative!r} was altered")
    return content


@functools.cache
def _recording(recording_id: str) -> dict[str, Any]:
    known = {entry["recording_id"] for entry in _manifest()["recordings"]}
    if recording_id not in known:
        raise LaboratoryDataError(f"the laboratory has no recording {recording_id!r}")
    payload = json.loads(gzip.decompress(_verified(f"recordings/{recording_id}.json.gz")))
    if payload.get("recording_id") != recording_id:
        raise LaboratoryDataError("a laboratory recording file does not hold its own recording")
    return payload


def laboratory_index() -> dict[str, Any]:
    """Dataset identity, claim and the recordings index."""
    manifest = _manifest()
    return {
        "schema": manifest["schema"],
        "dataset_id": manifest["dataset_id"],
        "manifest_sha256": MANIFEST_SHA256,
        "generated_with": manifest["generated_with"],
        "claim": manifest["claim"],
        "plan": manifest["plan"],
        "recordings": manifest["recordings"],
    }


@functools.cache
def laboratory_model() -> dict[str, Any]:
    """The compiled model as plain data (bodies, geoms in body frames, joints)."""
    return json.loads(_verified("model.json"))


def _phase_spans(times: list[float], phases: list[str]) -> list[dict[str, Any]]:
    spans: list[dict[str, Any]] = []
    start = 0
    for index in range(1, len(phases) + 1):
        if index == len(phases) or phases[index] != phases[start]:
            spans.append(
                {"phase": phases[start], "start_s": times[start], "end_s": times[index - 1]}
            )
            start = index
    return spans


def recording_view(recording_id: str) -> dict[str, Any]:
    """A recording's metadata, summary, checks and frame catalogue, without the frames."""
    record = _recording(recording_id)
    frames = record["frames"]
    catalogue = {group: list(columns) for group, columns in frames["groups"].items()}
    return {
        "recording_id": record["recording_id"],
        "label": record["label"],
        "kind": record["kind"],
        "description": record["description"],
        "timestep_s": record["timestep_s"],
        "duration_s": record["duration_s"],
        "steps": record["steps"],
        "completed": record["completed"],
        "failure": record["failure"],
        "trajectory_sha256": record["trajectory_sha256"],
        "command_events": record["command_events"],
        "phase_spans": _phase_spans(frames["t"], frames["phase"]),
        "summary": record["summary"],
        "extrema": record["extrema"],
        "work": record["work"],
        "numerics": record["numerics"],
        "checks": record["checks"],
        "frame_count": frames["count"],
        "sample_period_s": frames["t"][1] - frames["t"][0] if frames["count"] > 1 else 0.0,
        "body_names": frames["body_names"],
        "frame_groups": catalogue,
    }


def frame_columns(recording_id: str, group: str) -> list[tuple[str, list[float]]]:
    """One group's frame columns, ``t`` first, as ``(name, values)`` pairs."""
    if group not in FRAME_GROUPS:
        raise LaboratoryDataError(f"the laboratory has no frame group {group!r}")
    frames = _recording(recording_id)["frames"]
    columns = [("t", [float(value) for value in frames["t"]])]
    columns += [(name, values) for name, values in frames["groups"][group].items()]
    return columns
